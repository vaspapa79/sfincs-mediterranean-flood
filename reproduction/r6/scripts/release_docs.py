CODE17_LINE = ("- 2026-10-21T13:01:50Z — CODE-17 received (release prep, anonymised review copy, records); A: README, CHANGELOG.md, "
               "CITATION 1.4.2, the CODE-10 leftovers (YAML status lines, per-AOI-catchment rainfall `phase5/crete_rain_per_aoi.*`, "
               "these stage rows, tag `emsr933-v1`); no model run.")
ROW_MARK = "| GO-D6 + Phase 2"


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=True, encoding="utf-8").stdout


def commit_utc(repo: Path, rev: str) -> str:
    epoch = int(git(repo, "log", "-1", "--format=%ct", rev).strip())
    return dt.datetime.fromtimestamp(epoch, dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def tags(repo: Path) -> list[dict]:
    out = []
    fmt = "%(refname:short)\t%(objecttype)\t%(*objectname:short)\t%(objectname:short)\t%(creatordate:unix)\t%(contents:subject)"
    for ln in git(repo, "for-each-ref", "--sort=creatordate", f"--format={fmt}", "refs/tags").splitlines():
        name, typ, peeled, obj, epoch, subj = ln.split("\t")
        out.append({"name": name, "commit": peeled or obj, "date": dt.datetime.fromtimestamp(int(epoch), dt.timezone.utc).strftime("%Y-%m-%d"),
                    "annotated": typ == "tag", "subject": subj.strip()})
    return out


def defects(repo: Path) -> dict[str, dict]:
    with open(repo / "reproduction/r6/tables/S10.csv", newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    key = {k: next(c for c in rows[0] if c.startswith(k)) for k in ("defect", "symptom", "runs affected", "fix commit", "tag", "guard")}
    return {r[key["defect"]]: {k: r[c] for k, c in key.items()} for r in rows}


def defect_line(d: dict) -> str:
    fix = f"fix `{d['fix commit']}`" if d["fix commit"] not in ("", "—") else "no code change"
    guard = d["guard"].replace("tests: ", "") if d["guard"].startswith("tests: ") else d["guard"]
    return f"- **{d['defect']}** {d['symptom']} — runs affected: {d['runs affected']} — {fix} — guard: {guard}"


def changelog(repo: Path) -> str:
    tg = tags(repo)
    dd = defects(repo)
    release = [t for t in tg if t["name"].startswith("v")]
    last = release[-1]
    unreleased = git(repo, "log", "--format=%h %s", f"{last['name']}..HEAD").splitlines()
    L = ["# Changelog", "",
         "Releases of this repository, newest first. The defect lines D1–D8 are copied from "
         "`reproduction/r6/tables/S10.csv` (generated by `reproduction/r6/scripts/r6_tables.py` from `docs/AUDIT.md`, git and "
         "the tests); \"runs affected\" counts the release-v1.3.0 runs behind the earlier results. Tag dates, commits and "
         "summaries are read from git. Generated by `reproduction/r6/scripts/release_docs.py`.", ""]
    if unreleased:
        L += [f"## Unreleased (after tag `{last['name']}`; records and documentation only, harness unchanged)", ""]
        L += [f"- `{ln.split(' ', 1)[0]}` {ln.split(' ', 1)[1]}" for ln in reversed(unreleased)]
        L += ["- this commit: README, CHANGELOG.md, CITATION.cff 1.4.2, EMSR933 close-out (YAML status lines, per-AOI-catchment "
              "rainfall, timing rows, tag `emsr933-v1`)", ""]
    by_tag: dict[str, list[dict]] = {}
    for d in dd.values():
        by_tag.setdefault(d["tag"], []).append(d)
    for t in reversed(release):
        head = f"## {t['name']} — {t['date']} (tag `{t['name']}` → `{t['commit']}`)"
        if t["name"] == "v1.3.0":
            head += " — superseded – see D1–D8"
        elif t["name"] < "v1.3.0" or t["name"].startswith("v."):
            head += " — superseded"
        L += [head, "", f"{t['subject']}", ""]
        rows = sorted(by_tag.get(t["name"], []), key=lambda d: d["defect"])
        if t["name"] == "v1.4.0":
            rows = sorted(rows + by_tag.get("—", []), key=lambda d: d["defect"])
        L += [defect_line(d) for d in rows]
        if rows:
            L.append("")
    return "\n".join(L).rstrip() + "\n"


def stage_rows(repo: Path) -> list[str]:
    rows = []
    for s in STAGES:
        end = s.get("end_utc") or commit_utc(repo, s["end_commit"])
        t0 = dt.datetime.strptime(s["start_utc"], "%Y-%m-%dT%H:%M:%SZ")
        t1 = dt.datetime.strptime(end, "%Y-%m-%dT%H:%M:%SZ")
        mins = int(round((t1 - t0).total_seconds() / 60.0))
        rows.append(f"| {s['stage']} | {s['start_utc']} | {end} | {mins // 60} h {mins % 60:02d} min | {mins / 60.0:.1f} | _to fill_ | | {s['notes']} |")
    return rows


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True, type=Path)
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    cl = changelog(a.repo)
    rows = stage_rows(a.repo)
    print(cl)
    print("\n".join(rows))
    if a.write:
        (a.repo / "CHANGELOG.md").write_text(cl, encoding="utf-8")
        tp = a.repo / "reproduction/emsr933/timing.md"
        lines = tp.read_text(encoding="utf-8").split("\n")
        if any(r.split(" | ")[0] in lines[i] for r in rows for i in range(len(lines))):
            print("timing.md: stage rows already present, not inserted")
        else:
            i = next(k for k, ln in enumerate(lines) if ln.startswith(ROW_MARK))
            lines[i + 1:i + 1] = rows
            while lines and lines[-1] == "":
                lines.pop()
            lines.append(CODE17_LINE)
            tp.write_text("\n".join(lines) + "\n", encoding="utf-8")
            print(f"timing.md: {len(rows)} stage rows inserted after the GO-D6 row; CODE-17 line appended")
    return 0


if __name__ == "__main__":
    sys.exit(main())
