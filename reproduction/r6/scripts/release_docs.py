def stage_rows(repo: Path) -> list[str]:
    rows = []
    for s in STAGES:
        end = s.get("end_utc") or commit_utc(repo, s["end_commit"])
        t0 = dt.datetime.strptime(s["start_utc"], "%Y-%m-%dT%H:%M:%SZ")
        t1 = dt.datetime.strptime(end, "%Y-%m-%dT%H:%M:%SZ")
        mins = int(round((t1 - t0).total_seconds() / 60.0))
        rows.append(f"| {s['stage']} | {s['start_utc']} | {end} | {mins // 60} h {mins % 60:02d} min | {mins / 60.0:.1f} | _to fill_ | | {s['notes']} |")
    return rows


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True, type=Path)
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    cl = changelog(a.repo)
    rows = stage_rows(a.repo)
    print(cl)
    print("\n".join(rows))
    if a.write:
        (a.repo / "CHANGELOG.md").write_text(cl, encoding="utf-8")
        zd = a.repo / "reproduction/r6/ZENODO_DESCRIPTION_v1.4.2.md"
        zd.write_text(zenodo_description(a.repo), encoding="utf-8")
        print(f"wrote {zd.relative_to(a.repo)}")
        tp = a.repo / "reproduction/emsr933/timing.md"
        lines = tp.read_text(encoding="utf-8").split("\n")
        if any(r.split(" | ")[0] in lines[i] for r in rows for i in range(len(lines))):
            print("timing.md: stage rows already present, not inserted")
        else:
            i = next(k for k, ln in enumerate(lines) if ln.startswith(ROW_MARK))
            lines[i + 1:i + 1] = rows
            while lines and lines[-1] == "":
                lines.pop()
            lines.append(CODE17_LINE)
            tp.write_text("\n".join(lines) + "\n", encoding="utf-8")
            print(f"timing.md: {len(rows)} stage rows inserted after the GO-D6 row; CODE-17 line appended")
    return 0


if __name__ == "__main__":
    sys.exit(main())
