"""CODE-22 step 1 — docs/COMMIT_MAP_2026-10-23.md, rendered from the rewrite record (nothing retyped).

Reads reproduction/v14_rerun/code21/history_rewrite.json (filter-repo's commit-map and ref-map, with checks (a)-(e)) and git (date
and subject of each rewritten commit). Writes the map of the 34 rewritten commits (7-character and full hashes), the eight
removed paths, the reason, the statement that every tree is byte-identical apart from the removed files, and the tag map.

Usage: python -I code22_commit_map_doc.py --repo <worktree> [--print]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

RECORD = Path("reproduction/v14_rerun/code21/history_rewrite.json")
OUT = Path("docs/COMMIT_MAP_2026-10-23.md")
PUBLISHED_BASE = "ccd423a"


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=True, encoding="utf-8").stdout.strip()


def render(repo: Path) -> str:
    p = repo / RECORD
    rec = json.loads(p.read_text(encoding="utf-8"))
    rows = rec["commit_map"]
    changed = [r for r in rows if r["old"] != r["new"]]
    same = [r for r in rows if r["old"] == r["new"]]
    meta = {}
    for r in rows:
        d, s = git(repo, "log", "-1", "--format=%cI%x09%s", r["new"]).split("\t", 1)
        meta[r["new"]] = (d, s.replace("|", "/"))
    changed.sort(key=lambda r: meta[r["new"]][0])
    same.sort(key=lambda r: meta[r["new"]][0])
    checks = rec["checks"]
    tags = checks["c_tags_annotated_unchanged_text_repointed"]["tags"]
    L = ["# Commit map of the history rewrite of 2026-10-23", "",
         f"Generated by `reproduction/v14_rerun/scripts/code22_commit_map_doc.py` from `{RECORD.as_posix()}` (SHA-256 "
         f"{hashlib.sha256(p.read_bytes()).hexdigest()[:16]}…, written {rec['utc']} by `code21_history_rewrite_record.py`).", "",
         "## Why the history was rewritten", "",
         "Eight files with third-party station data (rain-gauge records of the NOA/meteo.gr network, which may not be redistributed) were "
         "tracked from the EMSR933 Stage-1 commit of 2026-10-09 until they were untracked on 2026-10-22. Before the first publication of that "
         "history they were removed from every commit that held them, with git filter-repo (CODE-21 item 4). Nothing else was changed.", "",
         "Removed paths:", ""]
    L += [f"- `{q}`" for q in rec["removed_paths"]]
    L += ["", "## What did not change", "",
          "Apart from the eight removed data files, the tree of every rewritten commit is byte-identical to the tree of its original: "
          "every code file, configuration, record and document is unchanged. Authors, committers, dates and commit messages are "
          "unchanged as well. The trees of `main` and `fix/harness-v1.4` at their tips are identical before and after the rewrite. "
          f"Commits up to and including the published v1.3.0 (`{PUBLISHED_BASE}`) kept their hashes, and so did the {len(same)} commits "
          "between v1.3.0 and the first commit that tracked the station files. Verified per commit: checks (b), (d) and (e) of the rewrite "
          "record, all " + ("PASS" if rec.get("all_pass") else "NOT PASSED") + ".", "",
          "## Reading a pre-rewrite hash", "",
          "Commit messages were kept verbatim, so the hashes they quote refer to the history before the rewrite; so do the hashes quoted in "
          "records dated before 2026-10-23 (the entries of `docs/AUDIT.md` before CODE-21, the `git_head` field of the run records, the "
          "checkpoints, the run manifest, the rule ledger and the timing log). They resolve through the table below. The published texts "
          "(CHANGELOG, README, Zenodo description, table S10) use the new hashes.", "",
          f"## The {len(changed)} rewritten commits (old → new)", "",
          "| # | old | new | committed | subject | old (full) | new (full) |", "|---|---|---|---|---|---|---|"]
    for i, r in enumerate(changed, 1):
        d, s = meta[r["new"]]
        L.append(f"| {i} | `{r['old'][:7]}` | `{r['new'][:7]}` | {d[:10]} | {s} | `{r['old']}` | `{r['new']}` |")
    L += ["", f"## The {len(same)} commits in the rewritten range that kept their hashes", ""]
    L += [f"- `{r['new'][:7]}` {meta[r['new']][0][:10]} {meta[r['new']][1]}" for r in same]
    L += ["", "## Tags", "",
          "| tag | tag object old → new | commit old → new |", "|---|---|---|"]
    L += [f"| `{t['tag']}` | `{t['old_tag']}` → `{t['new_tag']}` | `{t['old_commit']}` → `{t['new_commit']}` |" for t in tags]
    L += ["", "Tags up to v1.3.0 point at commits that kept their hashes. On 2026-10-23 tag `v1.4.2` was re-created, with the same "
          "message, on a release-metadata commit whose parent is the number-freeze commit above and which adds this file, CITATION.cff "
          "version 1.4.2, `.zenodo.json` and the published texts with the new hashes; that commit and the old → new tag target are "
          "recorded in `docs/AUDIT.md` (CODE-22), because a commit cannot quote its own hash.", ""]
    return "\n".join(L)


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True, type=Path)
    ap.add_argument("--print", action="store_true")
    a = ap.parse_args()
    repo = a.repo.resolve()
    doc = render(repo)
    if a.print:
        print(doc); return 0
    (repo / OUT).write_text(doc, encoding="utf-8")
    print(f"wrote {OUT.as_posix()} ({len(doc.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
