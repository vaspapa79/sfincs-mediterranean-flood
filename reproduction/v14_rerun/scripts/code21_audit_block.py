"""CODE-21 — AUDIT.md block for the pre-push close-out, rendered from the code21 records and the archive / anonymity records
(nothing retyped; every record cited with its SHA-256 prefix and UTC). Appends one section to docs/AUDIT.md unless --print.

Usage: python -I code21_audit_block.py --repo <worktree> [--print]
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import subprocess
import sys
from pathlib import Path


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=True, encoding="utf-8").stdout.strip()


def sha(p: Path, n: int = 16) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()[:n]


def render(repo: Path) -> str:
    c21 = repo / "reproduction" / "v14_rerun" / "code21"
    J = {}
    for n in ("history_rewrite", "push_plan", "zenodo_release_check"):
        p = c21 / f"{n}.json"
        J[n] = json.loads(p.read_text(encoding="utf-8")); J[n]["_sha"] = sha(p)
    r6 = repo / "reproduction" / "r6"
    b = json.loads((r6 / "review_archive_v1.4.2_build.json").read_text(encoding="utf-8"))
    an = json.loads((r6 / "ANONYMITY_REPORT_review_archive.json").read_text(encoding="utf-8"))
    now = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    head = git(repo, "rev-parse", "--short", "HEAD")
    tag = lambda n: f"`code21/{n}.json` (sha256 {J[n]['_sha']}…, {J[n]['utc']})"
    fe = repo / "docs" / "FREEZE_EVIDENCE.md"
    fs = repo / "reproduction" / "v14_rerun" / "scripts" / "fig_skill_sweeps_v14.py"
    hr = J["history_rewrite"]
    L = [f"## CODE-21 ({now}) — pre-push close-out (HEAD `{head}`; no model run; number freeze v1.4.2 stands; nothing pushed)", "",
         "Generated by `reproduction/v14_rerun/scripts/code21_audit_block.py`. Scripts: `code21_history_rewrite_record.py`, `d4_push_plan.py`, `code21_zenodo_check.py`, "
         "`build_review_archive.py`, `anonymity_grep.py --tree`, `release_docs.py --write`.", "",
         f"### 1 — docs/FREEZE_EVIDENCE.md first-score correction (file sha256 {sha(fe)}…)", "",
         "The Valencia first-score cell read 2026-07-15 21:00 local, which is the 350 mm run; the raw-IMERG run was scored at 2026-07-15T13:13:03Z = 16:13 local "
         "(`code20/b1_freeze_order.json`). The old value is kept struck through in the table and a dated correction paragraph gives the UTC sequence; the freeze ordering "
         "the file claims is unchanged.", "",
         f"### 2 — fig_skill_sweeps_v14.py superseded-benchmark note (file sha256 {sha(fs)}…)", "",
         "Header comment added: its BANDS (0.10–0.36, 0.42–0.62) and WING_MEDIAN are superseded by `code20/f10_benchmarks.json`; the PNG it draws is a phase-4 diagnostic "
         "of the v1.4.2 freeze, not the manuscript figure; output unchanged.", "",
         "### 3 — review archive rebuilt (local only, not uploaded)", "",
         f"- Built {b['utc']} from `git archive {b['tag']}` (`{b['tag_commit'][:7]}`, {b['files_from_tag']} files) + {b['overlay_files']} overlay files from HEAD `{b['head'][:7]}` "
         f"(now including `docs/FREEZE_EVIDENCE.md` and the code19 / code20 records); {len(b['excluded_files'])} files excluded (NOA station files, credentials patterns, caches, CITATION.cff, "
         f"CLAUDE.md, anonymity tooling, cited-work raw metadata, archived figures); {b['files_changed']} of {b['text_files']} text files scrubbed ({sum(b['substitutions'].values())} substitutions); "
         f"{b['n_files']} files in the archive.",
         f"- `{b['zip']['path']}`: {b['zip']['bytes'] / 1e6:.1f} MB, SHA-256 `{b['zip']['sha256']}`.",
         f"- Anonymity scan of the unpacked archive (`anonymity_grep.py --tree`, {an['utc']}): **{an['hits_outside_cited_work']} hits outside cited-work metadata**, "
         f"{an['hits_in_cited_work']} inside (other authors' Zenodo DOIs in refs_datacite.bib); by class: "
         + ", ".join(f"{k} {v}" for k, v in an["by_class"].items() if v) + "." + (f" Third-party github.com URLs listed, not counted: {an.get('third_party_github_urls', 0)}." if "third_party_github_urls" in an else ""), ""]
    L += [f"### 4 — history rewrite: NOA/meteo.gr station data files removed {tag('history_rewrite')}", "",
          f"Tool {hr['tool']['name']} {hr['tool']['version']}, {hr['tool']['git']}; command: `{hr['command']}`. {hr['commits_rewritten']} of {hr['commits_mapped']} commits after the "
          f"published v1.3.0 (`ccd423a`) rewritten, commit messages verbatim; removed paths: " + ", ".join(f"`{p}`" for p in hr["removed_paths"]) + "; kept (code and source notes, no station values): "
          + ", ".join(f"`{p}`" for p in hr["kept_noa_related_paths"]) + ".", "",
          "| ref | before | after |", "|---|---|---|"]
    for r in hr["ref_map"]:
        L.append(f"| `{r['ref']}` | `{r['old'][:7]}` | `{r['new'][:7]}` |")
    tagmap = {t["tag"]: t for t in hr["checks"]["c_tags_annotated_unchanged_text_repointed"]["tags"]}
    L += ["", "Tag targets (commits): " + "; ".join(f"`{t}` {v['old_commit']} → {v['new_commit']}" for t, v in tagmap.items()) + ". Earlier records that cite `0084600` (tag v1.4.2) now "
          "resolve to `" + tagmap.get("v1.4.2", {}).get("new_commit", "") + "`; the tree is identical.", "",
          "Checks (a)–(e) — the CODE-18 brief text was not available in this session, so these are the reconstruction recorded in the JSON:", ""]
    names = {"a_no_removed_path_in_pushed_history": "(a) no removed path reachable from main, v1.4.0, v1.4.1, v1.4.2, emsr933-v1",
             "b_rewritten_commits_differ_only_by_removed_paths_metadata_identical": "(b) every rewritten commit differs only by the removed paths; author / committer / dates / message identical",
             "c_tags_annotated_unchanged_text_repointed": "(c) tags annotated, tagger / date / message unchanged, re-pointed at the rewrite of the original target",
             "d_published_history_untouched": "(d) every commit up to v1.3.0 keeps its hash; origin/main is an ancestor of main; remote refs unchanged",
             "e_head_trees_unchanged_and_backups": "(e) HEAD trees of main and fix/harness-v1.4 identical before / after; backups present (refs/backup/code21/*, verified bundle)"}
    for k, label in names.items():
        c = hr["checks"][k]
        L.append(f"- {label}: **{'PASS' if c['pass'] else 'FAIL'}**")
    e = hr["checks"]["e_head_trees_unchanged_and_backups"]["bundle"]
    L += ["", f"Backup bundle of every ref before the rewrite: `{e['path']}` ({e['bytes'] / 1e6:.1f} MB, sha256 {e['sha256'][:16]}…, verified); the old refs also remain under "
          "`refs/backup/code21/` and the staging copies under `refs/rewritten/` (local only; delete after GO-PUSH is verified).", ""]
    pp = J["push_plan"]; zc = J["zenodo_release_check"]
    L += [f"### 5 — CHANGELOG, Zenodo description, push plan {tag('push_plan')} {tag('zenodo_release_check')}", "",
          f"`CHANGELOG.md` and `reproduction/r6/ZENODO_DESCRIPTION_v1.4.2.md` regenerated by `release_docs.py --write` (tag hashes read from git after the rewrite). "
          f"Creators of the existing Zenodo record {zc['existing_record']['doi']} (version {zc['existing_record']['version']}, concept {zc['existing_record']['concept_doi']}) against CITATION.cff: "
          f"{'identical' if zc['creators_check']['citation_cff_head_matches_zenodo_record'] else 'DIFFERENT'} ({zc['creators_check']['n_zenodo']} creators, same affiliation, ORCID only for the first). "
          f"The tag tree carries CITATION.cff version {zc['tag_tree_metadata']['citation_cff_version_at_tag']} and no .zenodo.json: {zc['tag_tree_metadata']['consequence']}", "",
          f"- Push command: `{pp['push_command']}` — refs: " + "; ".join(f"`{r['ref']}` → `{r['commit']}` ({r['action']})" for r in pp["refs"]) +
          f". `origin/main` = `{pp['origin_main'][:7]}`; `main` = `{pp['main'][:7]}`, {pp['ahead']} ahead, fast-forward {pp['fast_forward']}.",
          f"- Tracked at HEAD: NOA station data files {pp['tracked_noa_files'] or 'none'}; credential files {pp['tracked_credential_files'] or 'none'}; credential-like content hits "
          f"{len(pp.get('tracked_credential_content_hits', []))}. History reachable from the pushed refs: NOA data files {pp.get('history_noa_files') or 'none'}; credential files {pp.get('history_credential_files') or 'none'}.",
          "- GO-PUSH sequence: " + " → ".join(zc["go_push_sequence"][:3]) + ".", ""]
    return "\n".join(L)


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True, type=Path)
    ap.add_argument("--print", action="store_true")
    a = ap.parse_args()
    repo = a.repo.resolve()
    block = render(repo)
    if a.print:
        print(block); return 0
    audit = repo / "docs" / "AUDIT.md"
    txt = audit.read_text(encoding="utf-8")
    if "## CODE-21 (" in txt:
        raise SystemExit("docs/AUDIT.md already holds a CODE-21 block; remove it first")
    audit.write_text(txt.rstrip("\n") + "\n\n" + block.rstrip("\n") + "\n", encoding="utf-8")
    print(f"appended {len(block.splitlines())} lines to {audit}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
