"""CODE-17 — AUDIT.md block for the look-ups B1–B5 and the push preparation, rendered from the records (nothing retyped):
code17/lookups.json (B1–B4: values quoted from the sources, with the file behind each quote), code17/c6_alltouched_inflation.json
(B5), code17/BOX1_as_committed.md (B1 hashes), the review-archive build record and the anonymity scan of the archive when present,
and git (hashes, counts). Appends one section to docs/AUDIT.md unless --print.

Usage: python -I code17_audit_block.py --repo <worktree> [--print]
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import subprocess
import sys
from pathlib import Path


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=True, encoding="utf-8").stdout.strip()


def render(repo: Path) -> str:
    c17 = repo / "reproduction/v14_rerun/code17"
    lk = json.loads((c17 / "lookups.json").read_text(encoding="utf-8"))
    c6 = json.loads((c17 / "c6_alltouched_inflation.json").read_text(encoding="utf-8"))
    box = (c17 / "BOX1_as_committed.md").read_text(encoding="utf-8").splitlines()
    now = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    head = git(repo, "rev-parse", "--short", "HEAD")
    L = [f"## CODE-17 ({now}) — look-ups B1–B5, review archive and push preparation (HEAD `{head}`; no model run)", "",
         "Generated by `reproduction/v14_rerun/scripts/code17_audit_block.py` from `code17/lookups.json`, `code17/c6_alltouched_inflation.json`, "
         "`code17/BOX1_as_committed.md`, the archive build record and git. Quoted values carry the file and page behind them (raw sources in the "
         "CODE-17 attachments).", ""]
    b1 = lk["B1"]
    L += ["### B1 — when the frozen rule became public", "",
          f"- Rule frozen in the private manuscript-build repository: commit `{b1['origin_commit']}` ({b1['origin_date']}); never pushed to a public remote.",
          f"- Public copy: `{b1['public_file']}` added in `{b1['public_commit']}` (author date {b1['public_commit_date']}); the file's blob `{b1['blob']}` is unchanged at HEAD.",
          f"- First push of that commit to origin: {b1['first_push_utc']} ({b1['first_push_source']}).",
          f"- First public tag/release containing it: `{b1['first_tag']}` → `{b1['first_tag_commit']}`; GitHub release created {b1['first_release_created_utc']}, "
          f"published {b1['first_release_published_utc']}; Zenodo version {b1['first_zenodo_doi']} created {b1['first_zenodo_created_utc']} (publication_date {b1['first_zenodo_publication_date']}).",
          f"- Release v1.3.0 (the earlier manuscript's record): tag → `{b1['v130_commit']}`, GitHub release published {b1['v130_release_published_utc']}, Zenodo {b1['v130_zenodo_doi']} created {b1['v130_zenodo_created_utc']}. "
          f"Concept DOI {b1['concept_doi']} registered {b1['concept_registered_utc']} (predates the rule).",
          "- Box 1 as committed: `code17/BOX1_as_committed.md` — " + "; ".join(x.lstrip("- ") for x in box[3:6]), ""]
    b2 = lk["B2"]
    L += ["### B2 — Copernicus DEM citation and the GLO-30 release used", "",
          f"- `{b2['esa_doi']}`: registration agency {b2['esa_ra']} (DataCite API HTTP {b2['datacite_http']}; checked {b2['checked_utc']}). Crossref record: title {b2['crossref']['title']}, "
          f"authors {b2['crossref']['authors']}, publisher {b2['crossref']['publisher']}, issued {b2['crossref']['issued']}, type {b2['crossref']['type']}, no version field; doi.org resolves to {b2['resolves_to']}.",
          f"- `{b2['aws_doi']}` (DataCite): {b2['aws_record']}.",
          f"- `{b2['opentopo_doi']}` (DataCite): {b2['opentopo_record']} — not the distribution used; not to be cited.",
          f"- GLO-30 release used by every v1.4.x build (HydroMT data catalogue of each run, `data_catalog.yml`, entry `copdem30`): {b2['catalog_entry']}; the AWS collection "
          f"metadata states {b2['aws_release']}. Download: `skill/scripts/download_dem.py` from `{b2['bucket']}`, tiles `{b2['tile_pattern']}`.",
          f"- Licence notice for modified data (COP-DEM-GLO-30-F, Art. 6(b)): {b2['licence_notice']}", ""]
    b3 = lk["B3"]
    L += ["### B3 — Mandra event facts (Diakakis et al. 2019, doi 10.1016/j.ijdrr.2018.10.015; NOA Vilia)", "", f"- Access: {b3['access']}"]
    L += [f"- {x}" for x in b3["findings"]]
    L += [""]
    b4 = lk["B4"]
    L += ["### B4 — Valencia event facts (Chiva 491 mm in 8 h; Turís 772 mm in 24 h)", ""] + [f"- {x}" for x in b4["findings"]] + [""]
    L += ["### B5 — any-touched versus centre-point burning of the observed polygons (`code17/c6_alltouched_inflation.json`; S6)", "",
          "| event (run of record) | universe km² | observed cells any-touched | km² | observed cells centre | km² | inflation | CSI / HR / FAR / B any-touched | CSI / HR / FAR / B centre (re-scoring sensitivity) |",
          "|---|---|---|---|---|---|---|---|---|"]
    for e in c6["events"]:
        if e["event"] != "crete":
            u, lab = e["v14_universe"], f"{e['event']} ({e['run']})"
        else:
            u, lab = e["aois"]["03"], f"crete AOI03 tier 1 ({e['run']})"
        a, c = u["strict_h_gt_0p10"]["any_touched"], u["strict_h_gt_0p10"]["centre"]
        L.append(f"| {lab} | {u['universe_km2']:.1f} | {u['cells_any_touched']} | {u['observed_km2_any_touched']:.1f} | {u['cells_centre']} | {u['observed_km2_centre']:.1f} | "
                 f"+{u['inflation_pct']:.1f} % | {a['csi']:.3f} / {a['hr']:.3f} / {a['far']:.3f} / {a['bias']:.2f} | {c['csi']:.3f} / {c['hr']:.3f} / {c['far']:.3f} / {c['bias']:.2f} |")
    cr = next(e for e in c6["events"] if e["event"] == "crete")
    L += ["", "Crete tier-2 AOIs (area only): " + "; ".join(f"AOI{k} {v['cells_any_touched']} vs {v['cells_centre']} cells (+{v['inflation_pct']:.0f} %)" for k, v in sorted(cr["aois"].items()) if v["tier"] == 2) + ".",
          f"Method: {c6['definition']}. The any-touched contingency of every run reproduces its record (asserted). Release universe check: Pineios "
          f"+{[e for e in c6['events'] if e['event']=='pineios'][0]['release_universe']['inflation_pct']} %, Strymonas +{[e for e in c6['events'] if e['event']=='strymonas'][0]['release_universe']['inflation_pct']} %, "
          f"Mandra +{[e for e in c6['events'] if e['event']=='mandra'][0]['release_universe']['inflation_pct']} % (earlier text: +18 / +52 / +82 %).", ""]
    bj = repo / "reproduction/r6/review_archive_v1.4.2_build.json"
    sj = repo / "reproduction/r6/ANONYMITY_REPORT_review_archive.json"
    if bj.exists():
        b = json.loads(bj.read_text(encoding="utf-8"))
        z = b.get("zip", {})
        L += ["### C — anonymised review archive (local only, not uploaded)", "",
              f"- Built {b['utc']} from `git archive {b['tag']}` (`{b['tag_commit'][:7]}`, {b['files_from_tag']} files) + {b['overlay_files']} overlay files from HEAD `{b['head'][:7]}`; "
              f"{len(b['excluded_files'])} files excluded (NOA station files, credentials patterns, caches, CITATION.cff, CLAUDE.md, anonymity tooling, cited-work raw metadata, archived figures); "
              f"{b['files_changed']} of {b['text_files']} text files scrubbed ({sum(b['substitutions'].values())} substitutions); {b['n_files']} files in the archive.",
              f"- `{z.get('path')}`: {z.get('bytes', 0) / 1e6:.1f} MB, SHA-256 `{z.get('sha256')}`."]
        if sj.exists():
            sc = json.loads(sj.read_text(encoding="utf-8"))
            L.append(f"- Anonymity scan of the unpacked archive (`anonymity_grep.py --tree`, {sc['utc']}): {sc['hits_outside_cited_work']} hits outside cited-work metadata, "
                     f"{sc['hits_in_cited_work']} inside; by class: " + ", ".join(f"{k} {v}" for k, v in sc["by_class"].items() if v) + ".")
        L.append("")
    dj = c17 / "d4_push_plan.json"
    if dj.exists():
        d = json.loads(dj.read_text(encoding="utf-8"))
        ahead_after = int(git(repo, "rev-list", "--count", "origin/main..HEAD")) + 1       # this block's commit included
        refs = "; ".join(f"`{r['ref']}` → `{r['commit']}` ({r['action']})" for r in d["refs"])
        L += ["### D — push preparation (nothing pushed; GO-PUSH pending)", "",
              f"- Command: `{d['push_command']}` — refs: {refs}. `origin/main` = `{d['origin_main'][:7]}`; `main` is fast-forwarded to the commit that carries this block "
              f"({ahead_after} commits ahead of origin/main, fast-forward: {d['fast_forward']}).",
              f"- Tracked at HEAD ({d['utc']} check, `scripts/d4_push_plan.py`): NOA/meteo.gr station data files {d['tracked_noa_files'] or 'none'}; credential files "
              f"{d['tracked_credential_files'] or 'none'}; credential-like content {len(d['tracked_credential_content_hits'])} hit(s).",
              f"- History that the push would publish: {len(d['history_noa_files'])} NOA station data files were tracked from `{(d.get('history_first_commit_with_noa') or '')[:7]}` "
              f"(2026-10-09) until the commit before this one and are reachable from tags {', '.join('`' + t + '`' for t in d.get('history_tags_containing_noa_files', []))}; "
              f"credential files in history: {d['history_credential_files'] or 'none'}. Removing the station files from history would rewrite every commit since "
              "6363ead, including the frozen tag v1.4.2 — an author decision before GO-PUSH.", ""]
    return "\n".join(L) + "\n"


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True, type=Path)
    ap.add_argument("--print", action="store_true")
    a = ap.parse_args()
    block = render(a.repo)
    if a.print:
        print(block)
        return 0
    p = a.repo / "docs/AUDIT.md"
    txt = p.read_text(encoding="utf-8")
    if "## CODE-17 (" in txt:
        raise SystemExit("docs/AUDIT.md already has a CODE-17 block")
    p.write_text(txt.rstrip("\n") + "\n\n" + block, encoding="utf-8")
    print(f"appended {block.count(chr(10))} lines to docs/AUDIT.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
