"""CODE-20 — AUDIT.md block for the figure set after the benchmark correction, the three records and the S2 digest rows, rendered
from the code20 records (nothing retyped): every number carries the record it comes from, the record's SHA-256 and its UTC.
Appends one section to docs/AUDIT.md unless --print.

Usage: python -I code20_audit_block.py --repo <worktree> [--manuscript-txt <R6b text extract>] [--print]
"""
from __future__ import annotations

import argparse
import csv
import datetime as dt
import hashlib
import json
import subprocess
import sys
from pathlib import Path


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=True, encoding="utf-8").stdout.strip()


def sha(p: Path, n: int = 16) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()[:n]


def render(repo: Path, manuscript_txt: Path | None) -> str:
    c20 = repo / "reproduction" / "v14_rerun" / "code20"
    recs = {}
    for n in ("f10_benchmarks", "b1_freeze_order", "b3_emsr773_nested", "b4_sfincs_release"):
        p = c20 / f"{n}.json"
        recs[n] = json.loads(p.read_text(encoding="utf-8"))
        recs[n]["_sha"] = sha(p)
    now = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    head = git(repo, "rev-parse", "--short", "HEAD")
    figs = repo / "reproduction" / "r6" / "figures"

    def tag(n):
        return f"`code20/{n}.json` (sha256 {recs[n]['_sha']}…, {recs[n].get('utc')})"

    def figline(f):
        p = figs / f"{f}.tiff"
        return f"`{f}.tiff` (sha256 {sha(p)}…, {p.stat().st_size / 1e6:.1f} MB)" if p.exists() else f"`{f}.tiff` (missing)"
    L = [f"## CODE-20 ({now}) — figure set after the benchmark correction, three records, S2 digest rows (HEAD `{head}`; no model run; number freeze v1.4.2 stands)", "",
         "Generated by `reproduction/v14_rerun/scripts/code20_audit_block.py` from the records under `reproduction/v14_rerun/code20/` (each cited with its SHA-256 prefix and UTC). "
         "Scripts: `code20_lookups.py` (A1 quotes), `code20_b1_freeze_order.py`, `code20_b3_emsr773_nested.py`, `code20_b4_sfincs_release.py`; figures by `reproduction/r6/scripts/r6_figures.py`, "
         "tables by `r6_tables.py`. Nothing was simulated and no frozen number changed.", ""]
    # A1
    fb = recs["f10_benchmarks"]
    cst = fb["constants"]
    sq = fb["sources"]["sadana2026"]
    bq = fb["sources"]["bernhofen2018"]
    L += [f"### A1 — F10 v3 benchmark constants and their quotes {tag('f10_benchmarks')}", "",
          f"F10 v3: {figline('F10')}; markers unchanged (strict CSI, fuzzy r = 1 CSI, CSI*); y axis fixed {cst['ylim'][0]:.0f}–{cst['ylim'][1]:.1f}; the Hocini band is dropped; "
          "`r6_figures.fig10` asserts its constants against this record.", "",
          "| drawn element | constant | legend text | source | quote (printed page) |", "|---|---|---|---|---|",
          f"| grey band | {cst['band']['lo']:.2f}–{cst['band']['hi']:.2f} | {cst['band']['label']} | Bernhofen et al. 2018, ERL 13, 104007 (doi {bq['crossref']['doi']}); PDF sha256 {bq['document']['sha256'][:16]}… | "
          f"“{bq['quotes']['results']['quote']}” ({bq['quotes']['results']['printed_page']}); “{bq['quotes']['abstract']['quote']}” (abstract) |",
          f"| MODIS (band label) | — | — | same | “{bq['quotes'].get('modis', {}).get('quote')}” (PDF p. {bq['quotes'].get('modis', {}).get('pdf_page')}); Fig. 3 caption: “{bq['quotes'].get('modis_fig3', {}).get('quote')}” |",
          f"| dotted lines | {cst['lines'][0]['values'][0]:.2f} / {cst['lines'][0]['values'][1]:.2f} | {cst['lines'][0]['label']} | Sadana et al. 2026, HESS 30, {sq['bib_pages']} (doi {sq['doi']}; refs.bib `{sq['bib_key']}`); PDF sha256 {sq['document']['sha256'][:16]}… | "
          f"“{sq['quotes']['abstract_glofas_means']['quote']}” (p. {sq['quotes']['abstract_glofas_means']['printed_page']}); “{sq['quotes']['results_glofas_means']['quote']}” (p. {sq['quotes']['results_glofas_means']['printed_page']}); "
          f"Table 3: “{sq['quotes']['table3_large']['quote']}”, “{sq['quotes']['table3_small']['quote']}” (p. {sq['quotes']['table3_large']['printed_page']}); forcing: “{sq['quotes']['glofas_forcing']['quote']}” (p. {sq['quotes']['glofas_forcing']['printed_page']}) |",
          f"| dashed line | {cst['lines'][1]['values'][0]:.2f} | {cst['lines'][1]['label']} | same | “{sq['quotes']['observed_discharge_results']['quote']}” (p. {sq['quotes']['observed_discharge_results']['printed_page']}); "
          f"“{sq['quotes']['observed_discharge_discussion']['quote']}” (p. {sq['quotes']['observed_discharge_discussion']['printed_page']}) |",
          f"| not drawn | 0.39 | — | same | “{sq['quotes']['global_mean']['quote']}” (p. {sq['quotes']['global_mean']['printed_page']}); “{sq['quotes']['events']['quote']}” |", "",
          f"Reading: {sq['reading']} Previous F10 (v2) drew `fig_skill_sweeps_v14.BANDS` = {fb['previous_f10_v2']['fig_skill_sweeps_v14.BANDS']} "
          f"(and, until CODE-19 B1, the median line {fb['previous_f10_v2']['fig_skill_sweeps_v14.WING_MEDIAN']}); the phase-4 script of the v1.4.2 freeze is left unchanged and F10 v3 no longer reads it. "
          f"Fig. 10 caption of the R6b tracked manuscript (to be rewritten by the author): “{fb['previous_f10_v2'].get('fig10_caption_R6b_tracked')}”. "
          "The figure manifest's no-author-names rule (`r6_fig_manifest.py`) is relaxed for exactly these three legend labels (CODE-20 A1 wording).", ""]
    # A2 / A3
    L += ["### A2 — maps F3, F5, F6, F8, F9: exclusion mask above the depth layer", "",
          "`r6_figures.EXCL_ON_TOP` now covers every map (CODE-19 B4 had set F7 only): " + "; ".join(figline(f) for f in ("F3", "F5", "F6", "F8", "F9")) +
          f"; F7 unchanged from CODE-19 ({figline('F7')}). Legends unchanged; `FIGURES_MANIFEST.md` regenerated. The modelled water inside excluded cells that CODE-19 "
          "`b_maps_wet_in_excluded.json` counted (F3 47 km², F6 29, F8 130, F9 14, F5 0.8) is no longer visible; no score changes (the universe never held those cells).", ""]
    caps = {}
    if manuscript_txt and manuscript_txt.exists():
        for ln in manuscript_txt.read_text(encoding="utf-8").splitlines():
            for k in ("Fig. 3 ", "Fig. 5 ", "Fig. 6 ", "Fig. 7 ", "Fig. 8 ", "Fig. 9 "):
                if ln.startswith(k):
                    caps[k.strip()] = ln.strip()
    L += ["### A3 — map captions against the new draw order (report only; manuscript not edited)", ""]
    if caps:
        L += [f"R6b tracked manuscript (text extract sha256 {sha(manuscript_txt)}…):", ""]
        for k, v in caps.items():
            L.append(f"- {v}")
        L += ["", "Fig. 3 (“dark grey cells (permanent water, open sea) are excluded from the evaluation universe”) and Fig. 6 (“… excluded from the evaluation universe (dark grey)”) remain true "
              "and are now exact: with the mask drawn last, every excluded cell shows dark grey, whereas F3/F6/F8/F9 v2 overprinted modelled depth on part of them. Figs. 5, 7, 8 (“legend as Fig. 3”) "
              "and Fig. 9 (no grey statement; legend carries it) need no change. Optional, if the author wants the hiding stated: append to Fig. 3 “modelled water inside excluded cells is not drawn”.", ""]
    else:
        L += ["manuscript text extract not given; captions not checked here.", ""]
    # B1
    b1 = recs["b1_freeze_order"]
    o = b1["orders"]
    L += [f"### B1 — order of the rule freeze and the first Valencia metrics {tag('b1_freeze_order')}", "",
          "| event | source | as recorded | UTC |", "|---|---|---|---|"]
    pr = b1["private_repository"]
    if pr.get("present"):
        L += [f"| rule commit `bfd005a` | private repository git (author = committer) | {pr['bfd005a']['author_date']} | **{pr['bfd005a']['author_date_utc']}** |",
              f"| Valencia configuration written | mtime of runs/valencia_emsr773/valencia_emsr773_enhanced.yaml | — | {pr['valencia_run_dir_mtimes_utc'].get('valencia_emsr773_enhanced.yaml')} |",
              f"| first Valencia execution | mtime of run.log | — | {pr['valencia_run_dir_mtimes_utc'].get('run.log')} |",
              f"| first Valencia metrics (raw IMERG) | metrics.json generated_utc at `49da0d1` | {pr['49da0d1'].get('valencia_metrics_generated_utc')} | **{pr['49da0d1'].get('valencia_metrics_generated_utc')}** |",
              f"| commit `49da0d1` (results) | git | {pr['49da0d1']['author_date']} | {pr['49da0d1']['author_date_utc']} |",
              f"| 350 mm metrics | metrics.json generated_utc at `5447768` | {pr['5447768'].get('valencia_metrics_generated_utc')} | {pr['5447768'].get('valencia_metrics_generated_utc')} |",
              f"| commit `5447768` (350 mm) | git | {pr['5447768']['author_date']} | {pr['5447768']['author_date_utc']} |"]
        em = {k: v for k, v in pr["49da0d1"].get("metrics_files", {}).items() if "valencia" not in k}
        for k, v in em.items():
            L.append(f"| {k} at `49da0d1` | metrics.json generated_utc | {v} | {v} |")
    fe = b1["freeze_evidence_md"]
    L += [f"| docs/FREEZE_EVIDENCE.md author date | published record (sha256 {fe['sha256'][:16]}…) | {fe['author_date_as_written']} | {fe['author_date_utc']} |", "",
          f"**Verdict:** {b1['verdict']} (commit → first metrics {o['rule_commit_vs_first_valencia_metrics']['lead_hms']}; commit → configuration "
          f"{o.get('rule_commit_vs_valencia_config_mtime', {}).get('lead_hms')}; commit → first execution {o.get('rule_commit_vs_valencia_run_log_mtime', {}).get('lead_hms')}.) "
          f"Manuscript sentence (§3.4): “{b1['manuscript_sentence_section_3_4']}” — stands.", ""]
    if b1.get("freeze_evidence_discrepancy"):
        L += [f"Defect (report only): {b1['freeze_evidence_discrepancy']}", ""]
    # B2
    dig = repo / "reproduction" / "r6" / "tables" / "S2_baseline_digest.csv"
    L += ["### B2 — S2 digest rows (Strymonas ERA5 baseline)", ""]
    if dig.exists():
        with open(dig, encoding="utf-8", newline="") as fh:
            rd = csv.reader(fh); hdr = next(rd); rows = list(rd)
        L += [f"`tables/S2_baseline_digest.csv` (sha256 {sha(dig)}…), emitted by `r6_tables.tab_s2` as a sub-table of S2 (cells identical to the S2 rows of run `strymonas_baseline`):", "",
              "| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)] + ["| " + " | ".join(r) + " |" for r in rows] + [""]
    else:
        L += ["`tables/S2_baseline_digest.csv` missing.", ""]
    # B3
    b3 = recs["b3_emsr773_nested"]
    cn = b3["counts"]
    L += [f"### B3 — EMSR773 areas nested in AOI01 and their DEL products (response letter only) {tag('b3_emsr773_nested')}", "",
          f"Scope: {b3['scope']}. Of the {cn['aois_total']} EMSR773 AOIs, {cn['nested_in_aoi01_by_extent']} lie inside the AOI01 (Valencia province) extent and {cn['nested_and_in_model_domain']} of those hold "
          f"active cells of the model domain (the “23”). Nested AOIs with a DEL product: {', '.join(cn['nested_with_del_product'])}; in the domain: {', '.join(cn['nested_with_del_product_in_domain'])} "
          f"(outside: {', '.join(cn['nested_with_del_product_outside_domain'])}). Observed-event layers read from the EMS viewer (GeoJSON, each with URL / sha256 / bytes in the record); the AOI01 DEL_MONIT01 "
          f"GeoJSON reproduces the run's cached shapefile union ({b3['monit01_crosscheck']['union_km2']} km² both; {b3['monit01_crosscheck']['features']} features).", "",
          "| nested product (sensor, acquisition) | observed km² in the product: flooded area / flood trace / all (EMS API ha) | covered by AOI01 DEL_PRODUCT (31 Oct; S2/L8/S1): fraction of product all / flooded area; AOI01 observed inside the extent (km²), fraction of it inside the product | covered by AOI01 DEL_MONIT01 (3 Nov ICEYE; the truth used): same |",
          "|---|---|---|---|"]
    for key, row in b3["coverage"].items():
        n = int(key[3:5])
        ai = next(r for r in b3["aois"] if r["number"] == n)
        img = "; ".join(f"{s} {t[:10]}" for s, t in ai["del_products"][0]["images"])
        ob = row["observed_km2"]; st = row["api_stats_ha"] or {}
        def cov(rk):
            c = row["covered_by"][rk]
            fl = c["fraction_of_product_flooded_area_inside_aoi01_delineation"]
            return (f"{c['fraction_of_product_all_inside_aoi01_delineation'] * 100:.0f} % / {('—' if fl is None else f'{fl * 100:.0f} %')}; {c['aoi01_observed_km2_inside_this_extent']:.1f} km², "
                    f"{c['fraction_of_aoi01_observed_inside_extent_covered_by_product'] * 100:.0f} %")
        L.append(f"| {row['aoi']} ({img}) | {ob.get('Flooded area', 0):.2f} / {ob.get('Flood trace', 0):.2f} / {ob['all']:.2f} (API: flooded area {st.get('Flooded area', '—')} ha, flood trace {st.get('Flood trace', '—')} ha) | "
                 f"{cov('AOI01 DEL_PRODUCT')} | {cov('AOI01 DEL_MONIT01 (truth used)')} |")
    L += ["", "Reading: the province-level AOI01 delineation of 31 Oct covers most of the Algemesí polygons (93 % of all, 98 % of its flooded area) and roughly half of Horta Sud's (57 %; 74 % of its "
          "flooded area), but maps far more water inside each nested extent than the VHR nested products delineate (93 km² vs 11.7 at Algemesí; 67 km² vs 24.1 at Horta Sud). The AOI01 DEL_MONIT01 "
          "product of 3 Nov, the truth used in scoring, covers 9 % (Algemesí) and 1 % (Horta Sud) of the nested polygons: by 3 Nov the mapped water had largely receded. Yatova's product holds a "
          "0.01 km² flood trace that no AOI01 delineation maps. The nested products are therefore not the same polygons as the AOI01 truth; nothing was re-scored.", ""]
    # B4
    b4 = recs["b4_sfincs_release"]
    r = b4["release"]
    L += [f"### B4 — Deltares release of SFINCS v2.3.0 {tag('b4_sfincs_release')}", "",
          f"GitHub `Deltares/SFINCS` release **{r['name']}** (tag `{r['tag']}`), published {r['published_at']}, created {r['created_at']}, attached assets: {r['n_assets']} "
          f"(assets dated 2025-11-18: {len(r['assets_dated'])}); tag commit `{b4['tag_commit'].get('sha', '')[:7]}` dated {b4['tag_commit'].get('committer_date')} (“{b4['tag_commit'].get('message_first_line')}”). "
          f"Release text: " + " / ".join(f"“{x}”" for x in b4["release_body_distribution_lines"][:4]) + ". "
          f"Pre-release: {', '.join(p['name'] + ' (' + p['published_at'] + ')' for p in b4['pre_releases_of_v2_3_0'])}. "
          f"download.deltares.nl: {b4['deltares_download_page']['note'] if b4.get('deltares_download_page') else 'not fetched'}. "
          f"Binary as run (CODE-19 A3 record): {'; '.join(b4['binary_as_run']['sfincs_log_version_lines'])}. "
          f"API snapshot `{b4['github_api']['snapshot']}` (sha256 {b4['github_api']['sha256'][:16]}…, fetched {b4['github_api']['fetched_utc']}).", "",
          f"Answer: {b4['answer']} Proposed §3.1 wording (not applied): “{b4['proposed_section_3_1_wording']}”.", ""]
    L += ["### Tests", "", "`tests/test_code20_revision.py` (10 tests: F10 constants, map draw order, S2 digest, freeze-order helpers, nested-product coverage, release summary); full suite run recorded in the checkpoint.", ""]
    return "\n".join(L)


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True, type=Path)
    ap.add_argument("--manuscript-txt", type=Path, default=None)
    ap.add_argument("--print", action="store_true")
    a = ap.parse_args()
    repo = a.repo.resolve()
    block = render(repo, a.manuscript_txt)
    if a.print:
        print(block); return 0
    audit = repo / "docs" / "AUDIT.md"
    txt = audit.read_text(encoding="utf-8")
    if "## CODE-20 (" in txt:
        raise SystemExit("docs/AUDIT.md already holds a CODE-20 block; remove it first")
    audit.write_text(txt.rstrip("\n") + "\n\n" + block.rstrip("\n") + "\n", encoding="utf-8")
    print(f"appended {len(block.splitlines())} lines to {audit}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
