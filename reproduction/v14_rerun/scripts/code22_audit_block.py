"""CODE-22 — the AUDIT.md block, rendered from the code22 records (nothing retyped; each record cited with its SHA-256 prefix).

--part 1  (before the release-metadata commit exists; this part is carried by the re-created tag): the statement on pre-rewrite
          hashes, the commit map, the mapped texts and the grep check, CITATION.cff and .zenodo.json, the planned tag commit.
--part 2  (addendum, appended on the main line after the tag exists, because a commit cannot quote its own hash): the
          release-metadata commit and the old -> new tag targets, the merge into the main line, the review archive, the anonymity
          scan, the test run and the push plan.

Usage: python -I code22_audit_block.py --repo <worktree> --part 1|2 [--tests-log <unittest log>] [--print]
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

C22 = Path("reproduction/v14_rerun/code22")
TAG_FILES = ["docs/COMMIT_MAP_2026-10-23.md", "docs/AUDIT.md", "CHANGELOG.md", "README.md", "reproduction/r6/README_REVIEW.md",
             "reproduction/r6/ZENODO_DESCRIPTION_v1.4.2.md", "reproduction/r6/tables/S10.csv", "reproduction/r6/tables/S10.md",
             "CITATION.cff", ".zenodo.json"]


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=True, encoding="utf-8").stdout.strip()


def sha(p: Path, n: int = 16) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()[:n]


def load(repo: Path, name: str) -> dict:
    p = repo / C22 / f"{name}.json"
    d = json.loads(p.read_text(encoding="utf-8"))
    d["_tag"] = f"`code22/{name}.json` (sha256 {sha(p)}…, {d.get('utc', '')})"
    return d


def part1(repo: Path) -> str:
    now = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    gc = load(repo, "grep_check")
    cff = (repo / "CITATION.cff").read_text(encoding="utf-8")
    ver = re.search(r'^version:\s*"([^"]+)"', cff, re.M).group(1)
    date = re.search(r"^date-released:\s*(\S+)", cff, re.M).group(1)
    zj = json.loads((repo / ".zenodo.json").read_text(encoding="utf-8"))
    zr = repo / C22 / "zenodo_record_21488879.json"
    cm = repo / "docs" / "COMMIT_MAP_2026-10-23.md"
    n_rows = sum(1 for ln in cm.read_text(encoding="utf-8").splitlines() if re.match(r"\| \d+ \| `", ln))
    L = [f"## CODE-22 ({now}) — the history rewrite propagated to the published texts; v1.4.2 release metadata (HEAD `{git(repo, 'rev-parse', '--short', 'HEAD')}`; "
         "no model run; number freeze v1.4.2 stands; nothing pushed)", "",
         "**Commit hashes quoted in the entries of this file dated before 23 October 2026 refer to the history before the rewrite of "
         "2026-10-23 (CODE-21 item 4) and resolve through `docs/COMMIT_MAP_2026-10-23.md`. Those entries are not edited.** The same holds for "
         "the other dated records that quote them (listed under step 2).", "",
         f"Generated by `reproduction/v14_rerun/scripts/code22_audit_block.py --part 1`. Scripts: `code22_commit_map_doc.py`, `code22_grep_check.py`, "
         "`code22_release_commit.py`, `reproduction/r6/scripts/commit_map.py` (the mapper used by `r6_tables.py` and `release_docs.py`).", "",
         f"### 1 — commit map (`docs/COMMIT_MAP_2026-10-23.md`, sha256 {sha(cm)}…)", "",
         f"{n_rows} rewritten commits, old → new, 7-character and full hashes, from `code21/history_rewrite.json`; the eight removed paths; the reason "
         "(third-party station data); the statement that apart from the removed files every tree is byte-identical; the tag map.", "",
         f"### 2 — published texts mapped to the published hashes; grep check {gc['_tag']}", "",
         "| file | pre-rewrite hashes before | after |", "|---|---|---|"]
    for p in gc["published_texts"]:
        b = "new file" if p["pre_rewrite_hashes_at_HEAD"] is None else p["pre_rewrite_hashes_at_HEAD"]
        L.append(f"| `{p['file']}` | {b} | {p['pre_rewrite_hashes_now']} |")
    L += ["", "Table S10 is regenerated by `r6_tables.py`: the fix-commit column carries the published hashes; the CSV keeps the pre-rewrite hash in a "
          "last column, `pre-rewrite fix commit`, which the .md does not show. `release_docs.py` maps every rendered text (the CHANGELOG copies a tag "
          "message that quotes a pre-rewrite hash), and its stage list now quotes published hashes, so it keeps working once the pre-rewrite objects are "
          "deleted.", "",
          f"Grep of the tracked tree (and new files) for the six pre-rewrite fix commits ({gc['searched'].split('(')[1].split(')')[0]}): "
          f"{gc['hits']} hits in {gc['files_with_hits']} files; **{gc['other_hits']} outside the categories below**:", ""]
    for c, v in gc["by_category"].items():
        paths = v["paths"]
        shown = "; ".join(paths[:6]) + (f"; … {len(paths) - 6} more" if len(paths) > 6 else "")
        L.append(f"- {c}: {v['files']} files, {v['hits']} hits — {shown}")
    dated = gc["by_category"].get("dated record", {"paths": []})["paths"]
    n_run = sum(1 for p in dated if "/results/" in p)
    n_ckpt = sum(1 for p in dated if "/CHECKPOINT" in p)
    rest = [p.split(" (")[0].split("/")[-1] for p in dated if "/results/" not in p and "/CHECKPOINT" not in p]
    L += ["", "The brief's target of no hit outside the commit map and this file is not met by design for three of these categories: the S10 CSV keeps "
          "the pre-rewrite column the brief asks for, the rewrite record is the source of the map, and the dated records are left as written, like the "
          f"entries of this file: the `git_head` field of {n_run} run records (the commit each run was executed with), {n_ckpt} checkpoints and "
          + ", ".join(f"`{r}`" for r in rest) + ".", "",
          f"### 3 — release metadata", "",
          f"- `CITATION.cff`: version {ver}, date-released {date} (the date of the re-created tag).",
          f"- `.zenodo.json` (sha256 {sha(repo / '.zenodo.json')}…): title and version from CITATION.cff, upload_type {zj['upload_type']}, licence {zj['license']}, "
          f"access {zj['access_right']}, {len(zj['creators'])} creators copied (name, affiliation, ORCID) from the API response of record 10.5281/zenodo.21488879 "
          f"(`code22/zenodo_record_21488879.json`, sha256 {sha(zr)}…), its keywords, the description rendered from the same lines as the Zenodo draft, "
          "related identifiers " + "; ".join(f"{r['relation']} {r['identifier']}" for r in zj["related_identifiers"]) + ". Zenodo uses `.zenodo.json` and "
          "ignores CITATION.cff when both are present (Zenodo help, “Zenodo JSON file”); a related-identifier list there replaces the GitHub default, so the "
          "isSupplementTo link to the tag's tree is written explicitly.",
          "- Tag: `v1.4.2` is re-created (annotated, same message) on a release-metadata commit whose parent is the number-freeze commit `779a8e0` and whose "
          "tree is the freeze tree plus exactly these files, at their versions on the main line: " + ", ".join(f"`{f}`" for f in TAG_FILES) + ". That commit, "
          "the old → new tag target and `git diff --stat 779a8e0 v1.4.2` are recorded in the addendum below, appended on the main line once the tag exists.", ""]
    return "\n".join(L)


def part2(repo: Path, tests_log: Path | None) -> str:
    now = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    rc = load(repo, "release_commit")
    pp = load(repo, "push_plan")
    r6 = repo / "reproduction" / "r6"
    b = json.loads((r6 / "review_archive_v1.4.2_build.json").read_text(encoding="utf-8"))
    an = json.loads((r6 / "ANONYMITY_REPORT_review_archive.json").read_text(encoding="utf-8"))
    t = rc["tag"]
    merge = git(repo, "log", "-1", "--merges", "--format=%h %s", "HEAD")
    tests = "not run"
    if tests_log and tests_log.exists():
        txt = tests_log.read_text(encoding="utf-8", errors="replace")
        m = re.search(r"Ran (\d+) tests? in ([\d.]+)s\s+(OK.*|FAILED.*)", txt)
        tests = f"{m.group(1)} tests, {m.group(3).strip()}" if m else "log without a result line"
    L = [f"### CODE-22 addendum ({now}) — tag re-created, merged, review archive, push plan", "",
         f"Generated by `code22_audit_block.py --part 2` from {rc['_tag']} and {pp['_tag']}.", "",
         f"- Release-metadata commit `{rc['commit'][:7]}` (“{rc['commit_subject']}”), parent `{rc['commit_parent'][:7]}` (the number-freeze commit); "
         f"its diff against the parent is exactly the {len(rc['files'])} files above: {rc['diff_is_exactly_the_files']}; every file byte-identical to the main line "
         f"(`{rc['src_commit'][:7]}`): {all(rc['blobs_equal_to_src'].values())}.",
         f"- Tag `{t['name']}`: tag object `{t['old_tag_object'][:7]}` → `{t['new_tag_object'][:7]}`; target `{t['old_target'][:7]}` → `{t['new_target'][:7]}`; annotated "
         f"{t['annotated']}; message unchanged {t['message_unchanged']} (“{t['message_subject'][:80]}…”); tagger {t['old_tagger']} → {t['new_tagger']} (re-created, not "
         f"backdated); `git diff 779a8e0 v1.4.2` lists exactly the files above: {t['diff_old_target_new_tag_is_exactly_the_files']}. Previous tag object kept at "
         f"`{t['backup_ref']}`.", "",
         "```", f"git diff --stat {rc['base_freeze_commit'][:7]} v1.4.2", rc["diff_stat"], "```", "",
         f"- Merged into the main line: `{merge}` (the tree is unchanged by the merge; `v1.4.2` is now reachable from `main`).",
         f"- Review archive rebuilt from the new tag (`git archive v1.4.2` + the same overlays; `.zenodo.json`, the Zenodo draft and the repository copy of the "
         f"review README excluded): `{b['zip']['path']}`, **{b['zip']['bytes']} bytes ({b['zip']['bytes'] / 1e6:.1f} MB), SHA-256 `{b['zip']['sha256']}`** — "
         f"this replaces 2c0a3c6e… in the submission checklist; {b['n_files']} files ({b['files_from_tag']} from the tag, {b['overlay_files']} overlays, "
         f"{len(b['excluded_files'])} excluded); {b['files_changed']} of {b['text_files']} text files scrubbed.",
         f"- Anonymity scan of the unpacked archive ({an['utc']}): **{an['hits_outside_cited_work']} hits outside cited-work metadata**, {an['hits_in_cited_work']} inside; "
         f"third-party github.com URLs listed, not counted: {an.get('third_party_github_urls', 0)}.",
         f"- Tests: {tests}.",
         f"- Push plan ({pp['utc']}, computed on the commit before the one that carries this addendum): `{pp['push_command']}`; " + "; ".join(
             f"`{r['ref']}` → `{r['commit']}` ({r['action']})" for r in pp["refs"]) + f"; `origin/main` = `{pp['origin_main'][:7]}`, fast-forward "
         f"{pp['fast_forward']}; tracked NOA station data files {pp['tracked_noa_files'] or 'none'}, credential files {pp['tracked_credential_files'] or 'none'}, "
         f"credential-like content hits {len(pp.get('tracked_credential_content_hits', []))}; NOA data files in the pushed history "
         f"{pp.get('history_noa_files') or 'none'}. `main` is fast-forwarded to the commit that carries this addendum, one commit past the plan's.", ""]
    return "\n".join(L)


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True, type=Path)
    ap.add_argument("--part", required=True, choices=["1", "2"])
    ap.add_argument("--tests-log", type=Path, default=None)
    ap.add_argument("--print", action="store_true")
    a = ap.parse_args()
    repo = a.repo.resolve()
    block = part1(repo) if a.part == "1" else part2(repo, a.tests_log)
    if a.print:
        print(block); return 0
    audit = repo / "docs" / "AUDIT.md"
    txt = audit.read_text(encoding="utf-8")
    marker = "## CODE-22 (" if a.part == "1" else "### CODE-22 addendum ("
    if marker in txt:
        raise SystemExit(f"docs/AUDIT.md already holds '{marker}'; remove it first")
    audit.write_text(txt.rstrip("\n") + "\n\n" + block.rstrip("\n") + "\n", encoding="utf-8")
    print(f"appended {len(block.splitlines())} lines (part {a.part}) to {audit}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
